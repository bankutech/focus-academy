export function getBatchById(id) {
  return batchesData.find((b) => b.id === id) || null;
}

export function getBatchesByGrade(grade) {
  if (!grade || grade === 'all') return batchesData;
  return batchesData.filter((b) => b.grade.toLowerCase().includes(grade.toLowerCase()));
}

export function getBatchesBySlot(slotId) {
  if (!slotId) return batchesData;
  return batchesData.filter((b) => b.slotId === slotId);
}

export function getBatchesFiltered({ grade, board }) {
  return batchesData.filter((batch) => {
    if (grade && grade !== 'all') {
      const gNorm = grade.toLowerCase();
      if (gNorm.includes('6') || gNorm.includes('7') || gNorm.includes('8') || gNorm.includes('middle')) {
        if (!batch.grade.toLowerCase().includes('6 to 8') && !batch.grade.toLowerCase().includes('middle')) {
          return false;
        }
      } else if (gNorm.includes('9')) {
        if (!batch.grade.toLowerCase().includes('9')) return false;
      } else if (gNorm.includes('10')) {
        if (!batch.grade.toLowerCase().includes('10')) return false;
      } else if (gNorm.includes('11')) {
        if (!batch.grade.toLowerCase().includes('11')) return false;
      } else if (gNorm.includes('12')) {
        if (!batch.grade.toLowerCase().includes('12')) return false;
      }
    }

    if (board && board !== 'all') {
      const bNorm = board.toLowerCase();
      if (bNorm.includes('state') || bNorm.includes('samacheer')) {
        if (!batch.board.toLowerCase().includes('state') && !batch.board.toLowerCase().includes('samacheer')) {
          return false;
        }
      } else if (bNorm.includes('cbse')) {
        if (!batch.board.toLowerCase().includes('cbse')) {
          return false;
        }
      } else if (bNorm.includes('icse') || bNorm.includes('isc')) {
        if (!batch.board.toLowerCase().includes('icse') && !batch.board.toLowerCase().includes('isc')) {
          return false;
        }
      }
    }

    return true;
  });
}

export function resolveBoardForBatch(batch, currentBoard) {
  if (currentBoard) {
    const isState = currentBoard.includes('State') || currentBoard.includes('Samacheer');
    const isCbse = currentBoard.includes('CBSE');
    const isIcse = currentBoard.includes('ICSE') || currentBoard.includes('ISC');
    const bLower = (batch.board || '').toLowerCase();

    if (isState && (bLower.includes('state') || bLower.includes('samacheer'))) {
      return currentBoard;
    }
    if (isCbse && bLower.includes('cbse')) {
      return currentBoard;
    }
    if (isIcse && (bLower.includes('icse') || bLower.includes('isc'))) {
      return currentBoard;
    }
  }

  const bLower = (batch.board || '').toLowerCase();
  if (bLower.includes('cbse') && !bLower.includes('state')) return 'CBSE Board';
  if (bLower.includes('icse') && !bLower.includes('state')) return 'ICSE Board';
  return 'TN State Board (Samacheer)';
}

